// Carved relief blocks for black rock (D11.13). Reads etqws3's block
// sheet, reduces each top block's class map and raises it as a voxel
// heightfield, one .vox per top, which the game lays on carved black
// rock tops (view.carvedRelief).
//
//   node tools/carvevox.ts [--factor 2|4] [--heights 0,1,2,3,4] [--out DIR]
//
// --factor: how much the 32-texel map is reduced. 2 keeps the sheet's
//   16 x 16 pixels (columns 2 x 2 voxels); 4 merges 2 x 2 pixels by
//   majority (columns 4 x 4 voxels). Default 2.
// --heights: column height in voxels for each class (hole, groove, base,
//   lit edge, highlight). One voxel is 1/32 of a cell. Default 0,1,2,3,4.
// --out: output folder, default assets/generated.
// Output: carved-relief-0..7.vox, carved-relief.json (the settings used)
// and assets/preview/carved-relief.png.
//

import { mkdirSync, writeFileSync, readFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { writeVox } from "../src/vox/vox.ts";
import { decodePng } from "../src/vox/png.ts";
import { renderScene } from "../src/vox/render.ts";
import { CELL, carvedRelief } from "../src/assets/terrain.ts";
import { CARVED_SOURCE, CARVED_TOPS, CARVED_HEIGHTS, CARVED_FACTOR, carvedBlocks } from "../src/assets/carved.ts";

const ROOT = join(dirname(new URL(import.meta.url).pathname), "..");

function args(argv: string[]): { factor: number, heights: number[], out: string } {
  let factor = CARVED_FACTOR, heights = CARVED_HEIGHTS, out = join(ROOT, "assets", "generated");
  for (let k = 0; k < argv.length; k++) {
    const a = argv[k], v = argv[k + 1];
    if      (a === "--factor")  { factor  = Number(v); k++; }
    else if (a === "--heights") { heights = v.split(",").map(Number); k++; }
    else if (a === "--out")     { out     = v; k++; }
    else                        { throw new Error("unknown argument " + a); }
  }
  if ( (factor !== 2) && (factor !== 4) ) { throw new Error("--factor must be 2 or 4"); }
  if ( (heights.length !== 5) || heights.some(h => ( !Number.isInteger(h) || (h < 0) || (h > 16) )) ) {
    throw new Error("--heights needs five whole numbers in 0..16");
  }
  return { factor, heights, out };
}

const { factor, heights, out } = args(process.argv.slice(2));
mkdirSync(out, { recursive: true });
const blocks = carvedBlocks(decodePng(readFileSync(join(ROOT, CARVED_SOURCE))));
const models = CARVED_TOPS.map(([r, c], v) => {
  const m = carvedRelief([...blocks[(4 * r) + c]].map(Number), factor, heights);
  writeVox(join(out, "carved-relief-" + v + ".vox"), m);
  return m;
});
writeFileSync(join(out, "carved-relief.json"), JSON.stringify({
  license : "CC0-1.0",
  source  : "etqws3, Square Block Textures, https://opengameart.org/content/square-block-textures (CC0); see src/assets/carved.ts",
  note    : "Generated by tools/carvevox.ts. Heights in voxels by class: hole, groove, base, lit edge, highlight.",
  factor,
  heights,
  files   : models.map((_, v) => "carved-relief-" + v + ".vox"),
}, null, 1) + "\n");

// Preview: the eight blocks in a row; holes show the background.
//
const prev = join(ROOT, "assets", "preview");
mkdirSync(prev, { recursive: true });
const png = renderScene(models.map((m, i) => ({ m, ox: i * (CELL + 6), oy: 0, oz: 0 })), 4).png();
writeFileSync(join(prev, "carved-relief.png"), png);
console.log("carved relief: factor", factor, "heights", heights.join(","), "->", models.length, "blocks in", out);
